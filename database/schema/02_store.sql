-- Bảng danh mục sản phẩm, ví dụ Whey và Creatine.
CREATE TABLE IF NOT EXISTS categories (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name varchar(255) NOT NULL UNIQUE,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now()
);

-- Mỗi sản phẩm thuộc một danh mục; ảnh lưu trên Supabase Storage.
CREATE TABLE IF NOT EXISTS products (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  category_id integer NOT NULL REFERENCES categories(id) ON DELETE RESTRICT,
  name varchar(255) NOT NULL,
  description text,
  image_url text,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now()
);

-- Một sản phẩm có thể có nhiều phiên bản với giá và tồn kho riêng.
CREATE TABLE IF NOT EXISTS product_variants (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  product_id integer NOT NULL REFERENCES products(id) ON DELETE RESTRICT,
  flavor varchar(100),
  size varchar(100) NOT NULL,
  price decimal(12,2) NOT NULL CHECK (price >= 0),
  stock integer NOT NULL DEFAULT 0 CHECK (stock >= 0),
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now()
);

-- Mỗi người dùng có tối đa một giỏ hàng.
CREATE TABLE IF NOT EXISTS carts (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id integer NOT NULL UNIQUE REFERENCES users(id) ON DELETE RESTRICT,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now()
);

-- Một phiên bản sản phẩm chỉ xuất hiện một lần trong cùng một giỏ.
CREATE TABLE IF NOT EXISTS cart_items (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  cart_id integer NOT NULL REFERENCES carts(id) ON DELETE RESTRICT,
  variant_id integer NOT NULL REFERENCES product_variants(id) ON DELETE RESTRICT,
  quantity integer NOT NULL CHECK (quantity > 0),
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  UNIQUE (cart_id, variant_id)
);

-- Lưu thông tin giao hàng và số tiền tại thời điểm đặt hàng.
CREATE TABLE IF NOT EXISTS orders (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id integer NOT NULL REFERENCES users(id) ON DELETE RESTRICT,
  recipient_name varchar(255) NOT NULL,
  recipient_phone varchar(30) NOT NULL,
  shipping_address text NOT NULL,
  subtotal decimal(12,2) NOT NULL CHECK (subtotal >= 0),
  discount_amount decimal(12,2) NOT NULL DEFAULT 0 CHECK (discount_amount >= 0),
  total_amount decimal(12,2) NOT NULL CHECK (total_amount >= 0),
  status varchar(20) NOT NULL
    CHECK (status IN ('pending', 'confirmed', 'shipping', 'delivered', 'cancelled')),
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  CHECK (discount_amount <= subtotal),
  CHECK (total_amount = subtotal - discount_amount)
);

-- Giữ tên và giá của sản phẩm như lúc khách đặt hàng.
CREATE TABLE IF NOT EXISTS order_items (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  order_id integer NOT NULL REFERENCES orders(id) ON DELETE RESTRICT,
  variant_id integer NOT NULL REFERENCES product_variants(id) ON DELETE RESTRICT,
  product_name varchar(255) NOT NULL,
  variant_description varchar(255) NOT NULL,
  price decimal(12,2) NOT NULL CHECK (price >= 0),
  quantity integer NOT NULL CHECK (quantity > 0),
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now()
);

-- Một payment thuộc về đơn Store hoặc membership Gym.
CREATE TABLE IF NOT EXISTS payments (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id integer NOT NULL REFERENCES users(id) ON DELETE RESTRICT,
  order_id integer REFERENCES orders(id) ON DELETE RESTRICT,
  membership_id integer REFERENCES memberships(id) ON DELETE RESTRICT,
  amount decimal(12,2) NOT NULL CHECK (amount >= 0),
  payment_method varchar(30) NOT NULL
    CHECK (payment_method IN ('cod', 'bank_transfer')),
  status varchar(20) NOT NULL CHECK (status IN ('pending', 'completed')),
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  -- Bắt buộc một trong hai ID có giá trị, không được cùng có hoặc cùng trống.
  CHECK ((order_id IS NOT NULL) <> (membership_id IS NOT NULL))
);

-- Index hỗ trợ lọc theo danh mục, người dùng và các quan hệ thường tra cứu.
CREATE INDEX IF NOT EXISTS idx_products_category_id ON products(category_id);
CREATE INDEX IF NOT EXISTS idx_product_variants_product_id ON product_variants(product_id);
CREATE INDEX IF NOT EXISTS idx_cart_items_variant_id ON cart_items(variant_id);
CREATE INDEX IF NOT EXISTS idx_orders_user_id ON orders(user_id);
CREATE INDEX IF NOT EXISTS idx_orders_status_created_at ON orders(status, created_at);
CREATE INDEX IF NOT EXISTS idx_order_items_order_id ON order_items(order_id);
CREATE INDEX IF NOT EXISTS idx_order_items_variant_id ON order_items(variant_id);
CREATE INDEX IF NOT EXISTS idx_payments_user_id ON payments(user_id);
CREATE INDEX IF NOT EXISTS idx_payments_order_id ON payments(order_id);
CREATE INDEX IF NOT EXISTS idx_payments_membership_id ON payments(membership_id);
